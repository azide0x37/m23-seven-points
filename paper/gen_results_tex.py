def frac_tex(fr):
    if fr is None: return r'\text{--}'
    a, b = fr
    if b < 0: a, b = -a, -b
    if b == 1: return str(a)
    return rf'\tfrac{{{a}}}{{{b}}}'

def kelt_tex(re_, im_):
    """(a/b, c/d) -> (p + q*sqrt(-23))/r over common denominator."""
    if re_ is None or im_ is None: return r'\text{--}'
    from math import gcd
    a, b = re_; c, d = im_
    if b < 0: a, b = -a, -b
    if d < 0: c, d = -c, -d
    r = b*d // gcd(b, d)
    p, q = a*(r//b), c*(r//d)
    g = gcd(gcd(abs(p), abs(q)), r)
    p, q, r = p//g, q//g, r//g
    qs = f"{q}" if q < 0 else f"+{q}"
    return rf'\dfrac{{{p}{qs}\sqm}}{{{r}}}'

