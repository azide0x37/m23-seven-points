def cycles_tex(p):
    n = len(p); seen = [False]*n; out = []
    for i in range(n):
        if not seen[i] and p[i] != i:
            c = [i]; seen[i] = True; j = p[i]
            while j != i:
                c.append(j); seen[j] = True; j = p[j]
            out.append("(" + ",".join(str(k+1) for k in c) + ")")
        seen[i] = True
    return "".join(out) if out else "e"

